"""LLMClient — provider-independent interface for agent LLM calls."""

from __future__ import annotations

import logging
from abc import ABC, abstractmethod
from collections.abc import AsyncIterator

logger = logging.getLogger(__name__)


class LLMClientError(Exception):
    """Raised by LLMClient on unrecoverable failure.

    Attributes:
        provider:  Name of the provider that raised the error.
        retryable: True when a retry may succeed (transient error).
    """

    def __init__(
        self,
        message: str,
        provider: str = "",
        retryable: bool = False,
    ) -> None:
        super().__init__(message)
        self.provider = provider
        self.retryable = retryable


class LLMClient(ABC):
    """Provider-independent contract for generating LLM completions.

    Agent implementations depend only on this interface — not on GeminiProvider,
    OpenAIClient, or any other concrete class.

    ## Implementing an adapter

    ```python
    class MyAdapter(LLMClient):
        @property
        def provider_name(self) -> str:
            return "my_provider"

        @property
        def is_available(self) -> bool:
            return True

        async def generate(self, prompt: str, **kwargs) -> str:
            ...

        async def stream(self, prompt: str, **kwargs) -> AsyncIterator[str]:
            ...
    ```
    """

    @property
    @abstractmethod
    def provider_name(self) -> str:
        """Canonical provider identifier (e.g. ``"gemini"``, ``"gemma"``).

        Matches the existing ``LlmProvider.id`` values used on Android.
        """

    @property
    @abstractmethod
    def is_available(self) -> bool:
        """True when this client can currently serve requests."""

    @abstractmethod
    async def generate(
        self,
        prompt: str,
        *,
        system_prompt: str = "",
        conversation_id: str | None = None,
        user_id: str | None = None,
        max_tokens: int | None = None,
        temperature: float | None = None,
        rag_context: list[str] | None = None,
    ) -> str:
        """Generate a complete (non-streaming) text response.

        Args:
            prompt:          The user's message or assembled agent prompt.
            system_prompt:   Optional system / persona instruction.
            conversation_id: Identifier for structured logging.
            user_id:         User identifier for audit / rate-limiting.
            max_tokens:      Max tokens to generate; None = provider default.
            temperature:     Sampling temperature; None = provider default.
            rag_context:     RAG document snippets already assembled by caller.

        Returns:
            Generated text string.

        Raises:
            LLMClientError: On unrecoverable failure.
        """

    @abstractmethod
    def stream(
        self,
        prompt: str,
        *,
        system_prompt: str = "",
        conversation_id: str | None = None,
        user_id: str | None = None,
        max_tokens: int | None = None,
        temperature: float | None = None,
        rag_context: list[str] | None = None,
    ) -> AsyncIterator[str]:
        """Stream response tokens incrementally.

        Args: Same as generate().

        Yields:
            Token strings as generated by the provider.

        Raises:
            LLMClientError: On unrecoverable failure (wrapped in the
                                 async generator body).
        """


