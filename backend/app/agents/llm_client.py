class LLMServiceAdapter(LLMClient):
    """Wraps the existing :class:`~app.llm.service.LLMService` singleton.

    Bridges the agent LLMClient interface to the cloud LLM routing and
    fallback logic already implemented in LLMService.  **LLMService is not
    modified.**

    This adapter is created lazily so the heavy provider imports only happen
    when an agent actually calls the LLM.
    """

    def __init__(self) -> None:
        self._service: object | None = None

    def _get_service(self) -> object:
        if self._service is None:
            from app.llm.service import get_llm_service
            self._service = get_llm_service()
        return self._service

    @property
    def provider_name(self) -> str:
        return "gemini"

    @property
    def is_available(self) -> bool:
        # Optimistic: assume available; actual failures surface as exceptions
        return True

    async def generate(
        self,
        prompt: str,
        *,
        system_prompt: str = "",
        conversation_id: str | None = None,
        user_id: str | None = None,
        max_tokens: int | None = None,
        temperature: float | None = None,
        rag_context: list[str] | None = None,
    ) -> str:
        from app.llm.base import LLMRequest
        from app.llm.exceptions import LLMError

        req = LLMRequest(
            prompt=prompt,
            system_prompt=system_prompt,
            conversation_id=conversation_id,
            user_id=user_id,
            max_output_tokens=max_tokens,
            temperature=temperature,
            rag_context=rag_context or [],
        )
        try:
            svc = self._get_service()
            response = await svc.generate(req)  # type: ignore[attr-defined]
            return response.text
        except LLMError as exc:
            raise LLMClientError(
                str(exc),
                provider=self.provider_name,
                retryable=getattr(exc, "is_transient", False),
            ) from exc

    async def stream(  # type: ignore[override]
        self,
        prompt: str,
        *,
        system_prompt: str = "",
        conversation_id: str | None = None,
        user_id: str | None = None,
        max_tokens: int | None = None,
        temperature: float | None = None,
        rag_context: list[str] | None = None,
    ) -> AsyncIterator[str]:
        """Delegate streaming to LLMService (which delegates to GeminiProvider.stream)."""
        from app.llm.base import LLMRequest
        from app.llm.exceptions import LLMError

        req = LLMRequest(
            prompt=prompt,
            system_prompt=system_prompt,
            conversation_id=conversation_id,
            user_id=user_id,
            max_output_tokens=max_tokens,
            temperature=temperature,
            rag_context=rag_context or [],
        )
        try:
            svc = self._get_service()
            # LLMService.generate is used for non-streaming; for streaming we
            # call the resolved provider directly to get the async iterator.
            provider = svc._resolve_provider(req)  # type: ignore[attr-defined]
            async for token in provider.stream(req):
                yield token
        except LLMError as exc:
            raise LLMClientError(
                str(exc),
                provider=self.provider_name,
                retryable=getattr(exc, "is_transient", False),
            ) from exc


class LocalGemmaAdapter(LLMClient):
    """Wraps the existing :class:`~app.llm.providers.local_gemma_provider.LocalGemmaProvider`.

    Routes requests to a locally running Ollama Gemma model.
    **LocalGemmaProvider is not modified.**
    """

    def __init__(self, model_name: str = "gemma3:latest") -> None:
        self._model_name = model_name
        self._provider: object | None = None

    def _get_provider(self) -> object:
        if self._provider is None:
            from app.llm.providers.local_gemma_provider import LocalGemmaProvider
            self._provider = LocalGemmaProvider(model_name=self._model_name)
        return self._provider

    @property
    def provider_name(self) -> str:
        return "gemma"

    @property
    def is_available(self) -> bool:
        try:
            from app.config.settings import get_settings
            url = get_settings().OLLAMA_BASE_URL
            return bool(url and url.strip())
        except Exception:
            return False

    async def generate(
        self,
        prompt: str,
        *,
        system_prompt: str = "",
        conversation_id: str | None = None,
        user_id: str | None = None,
        max_tokens: int | None = None,
        temperature: float | None = None,
        rag_context: list[str] | None = None,
    ) -> str:
        from app.llm.base import LLMRequest
        from app.llm.exceptions import LLMError

        req = LLMRequest(
            prompt=prompt,
            system_prompt=system_prompt,
            conversation_id=conversation_id,
            user_id=user_id,
            max_output_tokens=max_tokens,
            temperature=temperature,
            rag_context=rag_context or [],
            complexity="local",
        )
        try:
            provider = self._get_provider()
            response = await provider.generate(req)  # type: ignore[attr-defined]
            return response.text
        except LLMError as exc:
            raise LLMClientError(
                str(exc), provider=self.provider_name, retryable=True
            ) from exc

    async def stream(  # type: ignore[override]
        self,
        prompt: str,
        *,
        system_prompt: str = "",
        conversation_id: str | None = None,
        user_id: str | None = None,
        max_tokens: int | None = None,
        temperature: float | None = None,
        rag_context: list[str] | None = None,
    ) -> AsyncIterator[str]:
        from app.llm.base import LLMRequest
        from app.llm.exceptions import LLMError

        req = LLMRequest(
            prompt=prompt,
            system_prompt=system_prompt,
            conversation_id=conversation_id,
            user_id=user_id,
            max_output_tokens=max_tokens,
            temperature=temperature,
            rag_context=rag_context or [],
            complexity="local",
        )
        try:
            provider = self._get_provider()
            async for token in provider.stream(req):  # type: ignore[attr-defined]
                yield token
        except LLMError as exc:
            raise LLMClientError(
                str(exc), provider=self.provider_name, retryable=True
            ) from exc

